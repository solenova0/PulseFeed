#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
command -v protoc >/dev/null || { echo 'Install protobuf-compiler (protoc) first.' >&2; exit 1; }
# Generator executables are pinned and installed in a task-specific temporary
# directory, avoiding mutation of the user's global Go binary directory.
tool_dir="$(mktemp -d)"
trap 'rm -rf "$tool_dir"' EXIT
GOBIN="$tool_dir" go install google.golang.org/protobuf/cmd/protoc-gen-go@v1.36.12
GOBIN="$tool_dir" go install google.golang.org/grpc/cmd/protoc-gen-go-grpc@v1.5.1
PATH="$tool_dir:$PATH" protoc -I proto \
  --go_out=gateway --go_opt=module=pulsefeed/gateway \
  --go-grpc_out=gateway --go-grpc_opt=module=pulsefeed/gateway \
  proto/pulsefeed.proto
echo 'Generated gateway/gen. C++ bindings are generated by CMake.'
